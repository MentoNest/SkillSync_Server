export enum ErrorCode {
  BAD_REQUEST = 'E_BAD_REQUEST',
  VALIDATION_ERROR = 'E_VALIDATION_ERROR',
  UNAUTHORIZED = 'E_UNAUTHORIZED',
  FORBIDDEN = 'E_FORBIDDEN',
  NOT_FOUND = 'E_NOT_FOUND',
  RESOURCE_NOT_FOUND = 'E_RESOURCE_NOT_FOUND',
  CONFLICT = 'E_CONFLICT',
  UNPROCESSABLE_ENTITY = 'E_UNPROCESSABLE_ENTITY',
  RATE_LIMITED = 'E_RATE_LIMITED',
  INTERNAL_ERROR = 'E_INTERNAL_ERROR',
  BAD_GATEWAY = 'E_BAD_GATEWAY',
  SERVICE_UNAVAILABLE = 'E_SERVICE_UNAVAILABLE',
  ERROR = 'E_ERROR',
}

export const STATUS_ERROR_CODES: Record<number, ErrorCode> = {
  400: ErrorCode.BAD_REQUEST,
  401: ErrorCode.UNAUTHORIZED,
  403: ErrorCode.FORBIDDEN,
  404: ErrorCode.NOT_FOUND,
  409: ErrorCode.CONFLICT,
  422: ErrorCode.UNPROCESSABLE_ENTITY,
  429: ErrorCode.RATE_LIMITED,
  500: ErrorCode.INTERNAL_ERROR,
  502: ErrorCode.BAD_GATEWAY,
  503: ErrorCode.SERVICE_UNAVAILABLE,
};

export function errorCodeFor(statusCode: number): ErrorCode {
  return STATUS_ERROR_CODES[statusCode] ?? ErrorCode.ERROR;
}
